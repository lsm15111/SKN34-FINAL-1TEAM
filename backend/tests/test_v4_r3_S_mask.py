def test_one_mask_for_check_guard_and_policy():
    """두 가림(v3 check · v2 guard)이 같은 함수 하나예요. policy.mask_in도 그 위에 제어 문자 손질만 더해요."""
    assert check.mask is pii.mask and guard.mask is pii.mask
    text = f"{QA} 이메일 kim@example.com{chr(0)}"
    assert policy.mask_in(text) == check.mask(QA + " 이메일 kim@example.com")
    # v2 답 검사도 같은 규칙으로 가린다(전에는 01x 전화 · 동 호만)
    out = guard.check("연락은 02-345-6789, 101동 1203로 해요.", "02 345 6789 101 1203").text
    assert "345-6789" not in out and "1203" not in out


