"""고침 3차 S 갈래 · 가림 빈틈(보안 QA r2 x1 N1): 호를 뺀 동호수 · 모음 'ㅡ' · 긴 줄표 구분 전화 · 띄어 쓴 주민번호 ·
은행 이름 · '계좌' 뒤 계좌의 앞자리, 날짜 · 금액 · 평형은 그대로, 가림 하나(v3 check · v2 guard · policy.mask_in).
DB 없음 · 유료 호출 0회."""

import pytest

from app.agent.v3 import check
from app.assistant import policy
from app.shared import pii
from app.v2 import guard

ZW, WJ, BOM = chr(0x200B), chr(0x2060), chr(0xFEFF)  # 폭 없는 빈칸 · 이음 · BOM

# x1 N1 재현 문장(그대로) → 가린 글
QA = (
    "저희 집은 101동 1203이에요. 주민번호 900101 1234567, 폰 010ㅡ1234ㅡ5678, "
    "계좌 카카오뱅크 3333-01-2345678로 받아요"
)
QA_MASKED = (
    "저희 집은 (동호수 가림)이에요. 주민번호 (주민번호 가림), 폰 (번호 가림), "
    "계좌 카카오뱅크 (계좌 가림)로 받아요"
)


def test_qa_sentence_is_masked_whole():
    got = check.mask(QA)
    assert got == QA_MASKED
    for needle in ("1203", "1234567", "5678", "3333", "2345678", "9(번호"):
        assert needle not in got, needle


