SGG: dict[str, set[str]] = {
    sid: {name for _, _, items in groups for name in items} for sid, (_, _, groups) in SIDO.items()
}


def is_region(sido: str, sgg: str) -> bool:
    return sgg in SGG.get(sido, set())


def region_label(sido: str, sgg: str) -> str:
    """화면에 보일 이름: 서울 마포구, 광주 광산구, 세종시"""
    for _, prefix, items in SIDO.get(sido, ("", "", []))[2]:
        if sgg in items:
            return f"{prefix} {sgg}" if prefix else sgg
    return sgg
