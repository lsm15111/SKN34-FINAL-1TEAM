"""개인정보 가림(security 8.5 · v4 고정 선 3). 사용자 글은 저장 · LLM 전에, AI 답은 보내기 전에 이 규칙 하나로 가린다.

- 가림: 주민등록번호(띄어 쓴 꼴 포함) · 계좌(은행 이름 · '계좌' 뒤, 단서가 없으면 하이픈 세 묶음 11~14자리) ·
  전화(국제 · 빗금 · 띄움 · 한글 숫자 · 여러 줄표 · 모음 'ㅡ') · 동호수(층 호 · 호를 뺀 '101동 1203' · 주소 가까이의
  101-1203) · 도로명 · 지번 번호 · 이메일(가린 꼴 포함) · 메신저 아이디.
- 두지 않음: 날짜(2026-12-14 · 12월 14일) · 금액(3,300,000원) · 평형(32평) · 법 · 고시 번호 · 대표번호. 지나치게
  가리면 숫자 검사와 답이 깨져요.
- agent/v3/check.mask · v2/guard.mask · assistant policy.mask_in이 모두 이 함수예요(전에는 v2 guard가 전화 · 동호수
  두 규칙을 따로 가졌어요, 보안 QA r2 N1). 화면 채팅 본문은 가리지 않는다(AI 입출력 · 기록용).
- 입구 관문 분류의 전처리(agent/intent.clean)는 학습 때와 같아야 해서 따로 둔다.
"""

import re

from app.shared.regions import EMD, SGG

# 숫자 묶음 사이 구분자: 빈칸 · 빗금 · 밑줄 · 점 · 여러 줄표(U+2010~2015 · 빼기 · 전각) · 모음 'ㅡ' · 상자 줄 '─ ━' ·
# 한자 '一' · 장음 'ー ｰ' · 붙임표 '⁃ ﹘ ﹣ ⸺ ⸻' · 가운뎃점 '· ‧ ・ ･ ∙'(N1: '010ㅡ1234ㅡ5678') · 붙여 넣을 때 끼는
# 폭 없는 글자(U+200B~200D · 2060 · FEFF)
_SEP = (
    r"[\s/_.\-\u2010-\u2015\u2212\uff0d\u3161\u2500\u2501\u4e00\u30fc\uff70\u2043\ufe58\ufe63"
    r"\u2e3a\u2e3b\u00b7\u2027\u30fb\uff65\u2219\u200b-\u200d\u2060\ufeff]"
)
_S = _SEP + "{0,3}"
# 숫자 뒤 단위 · 세는 말 · 범위(~): 이 말이 붙은 숫자는 주소 번호로 보지 않는다(금액 · 면적 · 날짜 · 개수)
_UNIT_AFTER = (
    r"(?!\s?(?:만|천|억|원|평|㎡|m|일|개|시|분|초|층|년|월|주|달|롤|%|번|장|명|곳|군데|가지|차|회|박|배"
    r"|살|세|등|위|점|퍼센트|문장|kg|cm|mm|[~∼〜]))"
)
# 동 · 호: '105동 1203호' · '101동 12호' · '1503호'. 법 · 고시 번호('대통령령 제36437호' · '제2026-360호')와 '3호선'은 빼요
DONGHO = re.compile(r"(?<![제\d-])(?:\d{1,4}\s*동\s*\d{1,4}\s*호|\d{3,4}\s?호)(?!선)")
# 호를 뺀 동 · 호('101동 1203', N1): 동 뒤 3~4자리. 금액 · 면적 · 날짜 · 세대 수(1동 300만 원 · 2동 1200세대)는 둔다
DONG_NO_HO = re.compile(
    r"(?<![제\d-])\d{1,4}\s*동\s*\d{3,4}"
    r"(?!\d|[.,]\d|\s?(?:만|천|억|원|평|㎡|년|월|일|세대|명|개|층|번|%|[~∼〜]))"
)
# '3층 2호'처럼 층 뒤 1~2자리 호(보안 QA M1)
FLOOR_HO = re.compile(r"(?<![\d-])\d{1,3}\s?층\s?\d{1,4}\s?호(?!선)")
# 주소 낱말 가까이(앞 ADDR_NEAR · 뒤 ADDR_AFTER 글자)의 '101-1203'(동-호 줄임). 날짜 · 금액 · 범위('100-200만 원')
# · 법 · 고시 번호('제2018-775호') · 대표번호('1661-2642')는 뺀다
DASH_UNIT = re.compile(
    r"(?<![\d.,\-/제])(?!1[5-9]\d{2}\s?-\s?\d{4}(?!\d))\d{2,4}\s?-\s?\d{3,4}(?:\s?호(?!선))?"
    r"(?![\d\-/]|[.,]\d)" + _UNIT_AFTER
)
# 도로명 주소의 건물 번호('동일로 1234' · '월계로45길 11'). 주소 낱말이 가까이 있을 때만이고, '…으로'(기준으로 3곳)
# · 단위가 붙은 숫자(실크로 34평) · 소수 · 천 단위 쉼표(3,300,000) · 흔한 낱말(도로 · 통로 …, ROAD_WORDS)은 둔다
ROAD_NO = re.compile(
    r"(?<![가-힣\d])([가-힣\d]{1,10}(?:대로|(?<!으)로|길))(?:\s?\d{1,4}\s?번?길)?\s?\d{1,4}(?:-\d{1,4})?"
    r"(?!\d|[.,]\d|\s?(?:번?길))" + _UNIT_AFTER
)
ROAD_WORDS = frozenset(
    {
        "도로", "통로", "경로", "차로", "진로", "선로", "철로", "수로", "활로", "항로", "대로", "산책로",
        "진입로", "출입로", "보행로", "고속도로", "골목길", "오솔길", "산길", "지름길", "갈림길", "비탈길",
        "오르막길", "내리막길", "둘레길", "큰길", "뒷길", "옆길",
    }
)  # fmt: skip
LOT_NO = re.compile(r"(?<![\d-])\d{1,5}(?:-\d{1,5})?\s?번지")  # 지번 '123-45번지'
# 주소 낱말: 주소 · 아파트 같은 말과 실제 시 · 군 · 구 · 법정동 이름(shared.regions). '고시' · '가구'처럼 시 · 구로
# 끝나는 낱말은 주소 낱말로 보지 않는다
_PLACES = sorted(
    {n for v in SGG.values() for n in v} | {n for v in EMD.values() for _, n in v},
    key=len,
    reverse=True,
)
ADDR_CUE = re.compile(
    r"주소|도로명|번지|아파트|단지|주공|빌라|맨션|오피스텔|동호수|(?<![가-힣])(?:"
    + "|".join(map(re.escape, _PLACES))
    + ")"
)
ADDR_NEAR, ADDR_AFTER = 40, 20
# 앞 글자가 같은 묶음이면 시작하지 않고 길이에 상한을 둬서 긴 입력에도 한 번만 훑어요(CodeQL ReDoS)
EMAIL = re.compile(r"(?<![\w.+-])[\w.+-]{1,64}@[\w-]{1,63}(?:\.[\w-]{1,63}){1,5}")
# 가린 꼴 이메일: kim.minsu(at)gmail.com · [at] · 골뱅이 · ' at ' · ' dot '(보안 QA M1)
EMAIL_ALT = re.compile(
    r"(?<![A-Za-z0-9._%+-])[A-Za-z0-9._%+-]{1,64}\s?"
    r"(?:\(at\)|\[at\]|\{at\}|<at>|\uff20|골뱅이|\sat\s)\s?"
    r"[A-Za-z0-9-]{1,63}(?:\s?(?:\.|\(dot\)|\[dot\]|\sdot\s|점)\s?[A-Za-z0-9-]{1,63}){1,5}",
    re.IGNORECASE,
)
# 메신저 아이디: '카톡 아이디 minsu88' · '아이디: minsu88'. 영문자가 하나는 든 낱말만(숫자만이면 계좌 · 번호 규칙)
MESSENGER = re.compile(
    r"((?:(?:카카오톡|카톡|카카오|텔레그램|인스타그램|인스타|위챗)(?:\s?(?:아이디|ID|계정))?"
    r"|(?:라인|네이버|구글)\s?(?:아이디|ID|계정)|아이디)\s?(?:[:：]|은|는)?\s?)"
    r"(@?(?=[A-Za-z0-9_.\-]{0,29}[A-Za-z])[A-Za-z0-9][A-Za-z0-9_.\-]{1,28}[A-Za-z0-9_])"
    r"(?![A-Za-z0-9_@]|[.\-][A-Za-z0-9_])"
)
# 주민등록번호(외국인 5~8 포함). 전화 · 계좌 규칙보다 먼저 가린다(앞뒤 숫자가 남고 이름표가 틀렸어요). 줄표가 아닌
# 구분자(띄움 '900101 1234567' 등, N1)나 붙여 쓴 꼴은 앞 6자리가 날짜일 때만, 뒤에 금액 · 면적 단위가 붙으면 둔다
_YMD = r"\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])"
RRN = re.compile(
    r"(?<!\d)\d{6}\s?-\s?[1-8]\d{6}(?!\d)"
    rf"|(?<!\d){_YMD}{_S}[1-8]\d{{6}}(?!\d|\s?[원만평㎡])"
)
# 계좌: 은행 이름 · '계좌(번호)' 바로 뒤의 숫자 묶음(숫자 10~14자리, 묶음 사이는 빈칸 · 줄표). 전화 규칙보다 먼저
# 가린다('카카오뱅크 3333-01-2345678'의 뒤만 전화로 가려 앞 4자리가 남았어요, N1). 날짜(2026-11-18)는 숫자가 모자라 둔다
_DASH = r"[\-\u2010-\u2015\u2212\uff0d\u3161]"
ACCOUNT = re.compile(
    r"((?:(?:국민|신한|우리|하나|농협|기업|카카오|토스|케이|새마을|우체국|수협|씨티|SC|산업|부산|대구|경남|광주|전북|제주)"
    r"(?:은행|뱅크)?|계좌(?:\s?번호)?)\s*(?:[:：]|은|는)?\s*)"
    rf"(\d(?:(?:\s|{_DASH}){{0,3}}\d){{8,24}})"
)
# 은행 이름 뒤라도 휴대폰 꼴이면 전화 규칙이 '번호'로 가린다
_MOBILE = re.compile(r"01[016789]\d{7,8}")
# 단서 없는 계좌(리드 결정 11-22): 하이픈으로만 이은 숫자 묶음 셋 이상 · 숫자 11~14자리 · 0으로 시작하지 않음
# ('3333-01-2345678' · '110-123-456789'). 전화(0으로 시작) · 사업자번호(3-2-5, 10자리) · 날짜(8자리) · 금액은 둔다.
# 국제 전화('82-10-3456-7890')는 먼저 가린 뒤에 본다
ACCOUNT_BARE = re.compile(r"(?<![\d\-.,+])(?!0)\d{1,8}(?:-\d{1,8}){2,5}(?![\d\-]|[.,]\d)")
# 전화 빈틈(보안 QA M1): 숫자 사이 빗금 · 밑줄 · 괄호 · 여러 칸, 국제번호(+82 · 82-10), 한 자리씩 띄운 번호,
# 한글 숫자('공일공 이삼사오 육칠팔구'). 날짜(2026-12-15 · 12.01) · 금액(3,300,000)과 겹치지 않게 0으로 시작하는
# 3 · 4 · 4(2 · 3~4 · 4) 묶음만 본다
PHONE_INTL = re.compile(
    rf"\+\s?82{_S}\(?0?\)?\s?\d{{1,2}}{_S}\d{{3,4}}{_S}\d{{4}}(?!\d)"
    rf"|(?<![\d+])82[\s\-.]{{1,3}}0?1[016789]{_S}\d{{3,4}}{_S}\d{{4}}(?!\d)"
)
# 앞뒤 숫자에 붙은 번호(오타 '010-1234-56789' 등)까지 잡는 그물(입구 관문 intent.PHONE · 옛 v2 guard.PHONE 꼴)
PHONE_ANY = re.compile(rf"[0\uff10]\d{{1,2}}{_SEP}?\d{{3,4}}{_SEP}?\d{{4}}")
PHONE_LOOSE = re.compile(rf"(?<![\d+])\(?[0\uff10]\d{{1,2}}\)?{_S}\d{{3,4}}{_S}\d{{4}}(?!\d)")
PHONE_SPACED = re.compile(rf"(?<![\d+])[0\uff10](?:{_SEP}{{1,3}}\d){{9,10}}(?![\d])")
PHONE_HANGUL = re.compile(
    r"(?<![가-힣])[공영]\s?일\s?[공영](?:[\s\-.]{0,2}[공영일이삼사오육칠팔구]){7,8}"
)


def _near_addr(sub: str):
    """주소 낱말이 앞 ADDR_NEAR 글자 · 뒤 ADDR_AFTER 글자 안에 있을 때만 가리는 바꾸기 함수. 도로명 꼴인데 길 이름이
    흔한 낱말(ROAD_WORDS: '주택단지 안의 도로 6.')이면 둔다."""

    def fn(m: re.Match) -> str:
        if m.re is ROAD_NO and m.group(1) in ROAD_WORDS:
            return m.group(0)
        s, a, b = m.string, m.start(), m.end()
        near = s[max(0, a - ADDR_NEAR) : a] + " " + s[b : b + ADDR_AFTER]
        return sub if ADDR_CUE.search(near) else m.group(0)

    return fn


def _account(m: re.Match) -> str:
    """은행 이름 뒤 숫자 묶음을 앞에서부터 14자리까지 모아 10자리 이상이면 가린다. 10자리를 넘긴 뒤에는 줄표로 이어진
    묶음만 더 모으고, 빈칸 뒤 다른 숫자(시각 · 전화 등)는 그대로 두어 다음 규칙이 본다. 휴대폰 꼴이면 전화 규칙에 맡긴다."""
    head, num = m.group(1), m.group(2)
    n, end = 0, 0
    for g in re.finditer(r"\d+", num):
        k = len(g.group())
        if n + k > 14 or (n >= 10 and not re.search(_DASH, num[end : g.start()])):
            break
        n, end = n + k, g.end()
    if n < 10 or _MOBILE.fullmatch(re.sub(r"\D", "", num[:end])):
        return m.group(0)
    return head + "(계좌 가림)" + num[end:]


def _bare_account(m: re.Match) -> str:
    """단서 없는 계좌 꼴: 숫자가 11~14자리일 때만 가린다(10자리 사업자번호 · 8자리 날짜는 둔다)."""
    return "(계좌 가림)" if 11 <= sum(c.isdigit() for c in m.group(0)) <= 14 else m.group(0)


def mask(text: str) -> str:
    """가림 모듈 하나(security 8.5). 화면 채팅 본문은 가리지 않는다(이 함수는 AI 입출력용).
    순서: 주민번호 → 계좌(은행 이름 · '계좌' 뒤) → 국제 전화 → 단서 없는 계좌(하이픈 세 묶음) → 전화(빗금 · 띄움 ·
    한글 숫자) → 동호수(층 호 · 호를 뺀 꼴 · 주소 가까이의 줄임) → 도로명 · 지번 → 이메일(가린 꼴 포함) → 메신저 아이디."""
    t = RRN.sub("(주민번호 가림)", text or "")
    t = ACCOUNT.sub(_account, t)
    t = PHONE_INTL.sub("(번호 가림)", t)
    t = ACCOUNT_BARE.sub(_bare_account, t)
    t = PHONE_ANY.sub("(번호 가림)", t)
    t = PHONE_LOOSE.sub("(번호 가림)", t)
    t = PHONE_SPACED.sub("(번호 가림)", t)
    t = PHONE_HANGUL.sub("(번호 가림)", t)
    t = FLOOR_HO.sub("(동호수 가림)", t)
    t = DONGHO.sub("(동호수 가림)", t)
    t = DONG_NO_HO.sub("(동호수 가림)", t)
    t = DASH_UNIT.sub(_near_addr("(동호수 가림)"), t)
    t = ROAD_NO.sub(_near_addr("(주소 가림)"), t)
    t = LOT_NO.sub("(주소 가림)", t)
    t = EMAIL.sub("(이메일 가림)", t)
    t = EMAIL_ALT.sub("(이메일 가림)", t)
    return MESSENGER.sub(lambda m: m.group(1) + "(아이디 가림)", t)
